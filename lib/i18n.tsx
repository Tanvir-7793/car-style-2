type Ctx = {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string) => string;
};

const I18nContext = createContext<Ctx | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    const saved = localStorage.getItem("carstyle-locale") as Locale | null;
    if (saved && ["en", "mr", "hi"].includes(saved)) setLocaleState(saved);
    // detect marathi browser
    const navLang = navigator.language.toLowerCase();
    if (!saved && navLang.startsWith("mr")) setLocaleState("mr");
    if (!saved && navLang.startsWith("hi")) setLocaleState("hi");
  }, []);

  useEffect(() => {
    localStorage.setItem("carstyle-locale", locale);
    document.documentElement.lang = locale === "mr" ? "mr" : locale === "hi" ? "hi" : "en";
    // toggle devanagari font class for mr/hi
    if (locale === "mr" || locale === "hi") document.documentElement.classList.add("devanagari");
    else document.documentElement.classList.remove("devanagari");
  }, [locale]);

  const setLocale = (l: Locale) => setLocaleState(l);

  const t = (key: string) => {
    return translations[locale]?.[key] ?? translations["en"][key] ?? key;
  };

  return <I18nContext.Provider value={{ locale, setLocale, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be inside LanguageProvider");
  return ctx;
}
