// Convert 0-9 to Devanagari digits for mr/hi
const devaDigits = ["०", "१", "२", "३", "४", "५", "६", "७", "८", "९"];
export function toLocalDigits(input: string | number, locale: Locale): string {
  if (locale === "en") return String(input);
  return String(input).replace(/[0-9]/g, (d) => devaDigits[parseInt(d)]);
}
export function toLocalPrice(price: string | number, locale: Locale): string {
  return `₹${toLocalDigits(price, locale)}`;
}

